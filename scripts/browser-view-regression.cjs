// Isolated real Electron WCV lifecycle + native popup checks; no model or merchant service.
const { app, BrowserWindow } = require('electron')
const { buildSync } = require('esbuild')
const { createServer } = require('node:http')
const { mkdtempSync, writeFileSync, mkdirSync, rmSync } = require('node:fs')
const { join } = require('node:path')
const { tmpdir } = require('node:os')
const assert = require('node:assert/strict')
const work = mkdtempSync(join(tmpdir(), 'plango-view-test-'))
app.setPath('userData', join(work, 'profile'))
app.commandLine.appendSwitch('host-resolver-rules', 'MAP fixture.meituan.com 127.0.0.1')
app.commandLine.appendSwitch('no-proxy-server')
app.commandLine.appendSwitch('disable-gpu')
app.on('window-all-closed', () => {})
let delayedRequested = false
const server = createServer((request, response) => {
  const send = () => { response.setHeader('content-type', 'text/html'); response.end('<!doctype html><title>Visible browser fixture</title><body style="background:#ea3344"><input id="name"><p>same-session fixture</p></body>') }
  if (request.url === '/slow') { delayedRequested = true; setTimeout(send, 600) } else send()
})
const sleep = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds))
async function waitFor(check) { for (let attempt = 0; attempt < 100; attempt++) { if (await check()) return; await sleep(50) } throw new Error('View state did not settle') }
let checks = 0
function check(condition, label) { assert(condition, label); checks++ }
async function main() {
  buildSync({ entryPoints: ['src/main/browserView.ts'], outfile: join(work, 'manager.cjs'), bundle: true, platform: 'node', format: 'cjs', external: ['electron'] })
  const manager = require(join(work, 'manager.cjs'))
  await app.whenReady()
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const url = `http://fixture.meituan.com:${server.address().port}/`
  const host = new BrowserWindow({ width: 900, height: 700, show: true, webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false } })
  writeFileSync(join(work, 'host.html'), '<!doctype html><title>PlanGo controlled shell</title><body style="background:#3355ee">host</body>')
  await host.loadFile(join(work, 'host.html'))
  manager.initializeBrowserViews(host)
  manager.setBrowserLayout({ x: 30, y: 80, width: 700, height: 450, visible: true })
  const first = await manager.createBrowserTab(url)
  check(host.contentView.children.length === 1 && manager.getBrowserTab(first.id) === first.contents, 'WCV is the actual manager-owned guest')
  check(manager.isOwnedBrowserContents(first.contents.id) && !manager.isOwnedBrowserContents(host.webContents.id), 'Ownership excludes shell contents')
  check(manager.isBrowserTabVisible(first.id), 'The active WCV is visible in the shown host')
  const initialSignal = manager.getBrowserTabSignal(first.id)
  check(!initialSignal.aborted && manager.getBrowserTabSignal('missing-tab').aborted, 'Only a visible existing tab has an active lifecycle signal')
  check(await first.contents.executeJavaScript("typeof require==='undefined'&&typeof window.plango==='undefined'"), 'Guest has no Node or privileged preload')
  await first.contents.executeJavaScript("localStorage.setItem('session-marker','same-profile')")
  const second = await manager.createBrowserTab(url + 'second')
  check(first.contents.session === second.contents.session && first.contents.id !== second.contents.id, 'Tabs share the same persistent session, with distinct contents')
  check(await second.contents.executeJavaScript("localStorage.getItem('session-marker')==='same-profile'"), 'Login storage is shared directly without copying')
  check(!manager.isBrowserTabVisible(first.id) && manager.isBrowserTabVisible(second.id), 'Only the selected tab is visible')
  check(initialSignal.aborted, 'Switching tabs synchronously aborts the previous visible cycle')
  manager.activateBrowserTab(first.id)
  check(manager.getBrowserTabSignal(first.id) !== initialSignal && !manager.getBrowserTabSignal(first.id).aborted, 'Returning to a tab creates a fresh cycle without cancelling the run')
  const abort = new AbortController()
  const cancelled = manager.loadBrowserURL(first.contents, url + 'slow', abort.signal).catch(error => error)
  await waitFor(() => delayedRequested)
  abort.abort()
  check((await cancelled).message === 'navigation_cancelled', 'Cancellation stops a pending native navigation')
  await sleep(700)
  check(first.contents.getURL() !== url + 'slow', 'A cancelled delayed response cannot navigate later')
  delayedRequested = false
  const superseded = new AbortController()
  const earlier = manager.loadBrowserURL(first.contents, url + 'slow', superseded.signal).catch(error => error)
  await waitFor(() => delayedRequested)
  await manager.loadBrowserURL(first.contents, url + 'manual')
  superseded.abort()
  check((await earlier).message === 'navigation_superseded', 'A new user navigation replaces only the previous native load')
  await sleep(700)
  check(first.contents.getURL() === url + 'manual', 'An old command abort cannot stop or replace the newer user navigation')
  await manager.handleBrowserIntent({ kind: 'zoom', id: first.id, factor: 1.4 })
  check(first.contents.getZoomFactor() === 1.4 && manager.getBrowserState().tabs.find(tab => tab.id === first.id).zoom === 1.4, 'Zoom and renderer metadata agree')
  const beforeOverlay = manager.getBrowserTabSignal(first.id)
  let overlayAborted = false
  beforeOverlay.addEventListener('abort', () => { overlayAborted = true }, { once: true })
  manager.setBrowserLayout({ x: 30, y: 80, width: 700, height: 450, visible: false })
  check(!manager.isBrowserTabVisible(first.id), 'Modal/hidden work area hides native guest')
  check(overlayAborted && beforeOverlay.aborted, 'Overlay abort reaches the driver synchronously before setBrowserLayout returns')
  await waitFor(async () => await first.contents.executeJavaScript('document.visibilityState') === 'hidden')
  checks++
  manager.setBrowserLayout({ x: 30, y: 80, width: 700, height: 450, visible: true })
  const beforePopup = manager.getBrowserTabSignal(first.id)
  check(beforePopup !== beforeOverlay && !beforePopup.aborted, 'Closing an overlay starts a fresh visible cycle')
  let inherited, publishedBeforeInheritance = false
  const send = host.webContents.send.bind(host.webContents)
  host.webContents.send = (channel, ...args) => {
    if (channel === 'browser:view-state' && args[0].tabs.some(tab => tab.popup) && !inherited) publishedBeforeInheritance = true
    return send(channel, ...args)
  }
  manager.onBrowserPopup((parentId, childId) => { inherited = { parentId, childId, attached: !!manager.getBrowserTab(childId), activeId: manager.getActiveBrowserTab()?.id } })
  await first.contents.executeJavaScript(`window.open(${JSON.stringify(url + 'popup')},'_blank');true`, true)
  await waitFor(() => manager.getBrowserState().tabs.some(tab => tab.popup))
  const popupId = manager.getBrowserState().tabs.find(tab => tab.popup).id
  host.webContents.send = send
  check(inherited?.parentId === first.id && inherited.childId === popupId && inherited.attached, 'Popup inheritance receives the exact attached parent/child identities')
  check(inherited.activeId === first.id && !publishedBeforeInheritance, 'Popup inheritance runs synchronously before activation or any state publication')
  const popup = manager.getBrowserTab(popupId), popupWindow = BrowserWindow.fromWebContents(popup)
  check(!!popupWindow && popup.session === first.contents.session && popupWindow.isVisible(), 'Popup is a real visible native BrowserWindow in the same session')
  check(beforePopup.aborted && !manager.getBrowserTabSignal(popupId).aborted, 'A popup taking the visible slot aborts its opener cycle')
  const beforeHostHide = manager.getBrowserTabSignal(popupId)
  host.hide()
  check(!popupWindow.isVisible(), 'Hiding the host also hides its native popup')
  check(beforeHostHide.aborted, 'Host hide aborts the popup cycle')
  host.show()
  check(popupWindow.isVisible(), 'Showing the host restores its active popup')
  check(manager.getBrowserTabSignal(popupId) !== beforeHostHide && !manager.getBrowserTabSignal(popupId).aborted, 'Host show refreshes the popup cycle')
  const beforePopupHide = manager.getBrowserTabSignal(popupId)
  popupWindow.hide()
  check(beforePopupHide.aborted, 'Native popup hide also aborts without relying on renderer layout')
  popupWindow.showInactive()
  check(!manager.getBrowserTabSignal(popupId).aborted, 'Native popup show creates a usable cycle')
  manager.setBrowserLayout({ x: 30, y: 80, width: 700, height: 450, visible: false })
  check(!popupWindow.isVisible(), 'A shell modal also hides its owned popup')
  manager.setBrowserLayout({ x: 30, y: 80, width: 700, height: 450, visible: true })
  const beforePopupClose = manager.getBrowserTabSignal(popupId)
  await manager.handleBrowserIntent({ kind: 'close', id: popupId })
  check(beforePopupClose.aborted && manager.getBrowserTabSignal(popupId).aborted, 'Closing cannot revive a lifecycle signal before destruction')
  await waitFor(() => !manager.getBrowserTab(popupId))
  check(!manager.getBrowserState().tabs.some(tab => tab.id === popupId), 'Closing popup removes canonical tab metadata')
  manager.setBrowserLayout({ x: 30, y: 80, width: 700, height: 450, visible: true })
  manager.activateBrowserTab(first.id)
  const beforeCrash = manager.getBrowserTabSignal(first.id)
  const crashed = new Promise(resolve => first.contents.once('render-process-gone', resolve))
  first.contents.forcefullyCrashRenderer()
  await crashed
  check(!!manager.getBrowserState().tabs.find(tab => tab.id === first.id)?.error, 'A renderer crash is recorded as a recoverable page error')
  check(!manager.isBrowserTabVisible(first.id), 'A crashed page exposes recovery UI instead of a stale native surface')
  check(beforeCrash.aborted, 'Crash immediately aborts the current cycle')
  await manager.handleBrowserIntent({ kind: 'reload', id: first.id })
  await waitFor(() => !first.contents.isLoading() && !manager.getBrowserState().tabs.find(tab => tab.id === first.id)?.error)
  check(await first.contents.executeJavaScript("localStorage.getItem('session-marker')==='same-profile'"), 'Native reload recovers the same persistent context')
  check(manager.getBrowserTabSignal(first.id) !== beforeCrash && !manager.getBrowserTabSignal(first.id).aborted, 'Crash recovery uses a new signal')
  manager.setBrowserLayout({ x: 9999, y: 9999, width: 9999, height: 9999, visible: true })
  check(!manager.isBrowserTabVisible(first.id), 'Out-of-window geometry cannot expose a native view')
  manager.setBrowserLayout({ x: 30, y: 80, width: 700, height: 450, visible: true })
  const evidence = join(process.cwd(), 'eval/plango-p1')
  mkdirSync(evidence, { recursive: true })
  await first.contents.executeJavaScript('new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))')
  writeFileSync(join(evidence, 'native-browser-view.png'), (await first.contents.capturePage()).toPNG())
  const beforeHostClose = manager.getBrowserTabSignal(first.id)
  host.close()
  check(beforeHostClose.aborted, 'Host close synchronously aborts every current cycle')
  await waitFor(() => manager.getBrowserState().tabs.length === 0)
  check(first.contents.isDestroyed() && second.contents.isDestroyed(), 'Host close releases every owned guest')
  console.log(`Browser view regression: ${checks} assertions passed (real Electron WCV/native popup, fixture session)`)
}
main().then(() => { server.close(); rmSync(work, { recursive: true, force: true }); app.exit(0) }).catch(error => { console.error(error); server.close(); rmSync(work, { recursive: true, force: true }); app.exit(1) })
